#!/usr/bin/env python3
"""Generate the CLI reference from a built Chopper executable."""

import argparse
import os
from pathlib import Path
import re
import subprocess


REFERENCE = Path(__file__).resolve().parents[1] / 'docs/cli-reference.md'


def render(binary):
    def cli(*args):
        output = subprocess.check_output(
            [binary, *args], encoding='utf-8', timeout=30,
            env={**os.environ, 'NO_COLOR': '1'},
        )
        output = re.sub(r'^Usage: chopper\.exe(?=\s|$)', 'Usage: chopper', output, flags=re.M)
        return '\n'.join(line.rstrip() for line in output.splitlines()).rstrip()

    def sections(path=()):
        help_text = cli('help', *path) if path else cli('--help')
        name = ' '.join(('chopper', *path))
        yield f'## `{name}`\n\n```text\n{help_text}\n```\n'
        # Clap lists visible subcommands in a separate, two-space-indented block.
        commands = re.search(r'^Commands:\n((?:  [^\n]+\n)+)', help_text + '\n', re.M)
        if commands:
            for line in commands[1].splitlines():
                yield from sections((*path, line.split()[0]))

    return '\n'.join([
        f'# CLI reference for {cli("--version")}',
        '',
        '<!-- Generated by scripts/cli-reference.py from the release binary help. -->',
        '',
        'Use `chopper --version` to find the matching release for your executable.',
        'See [Run modes and automation](run-cli.md), [saved Jobs](job-json.md), and',
        '[recipes](job-recipes.md).',
        '',
        *sections(),
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('binary', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    reference = render(args.binary.resolve())
    if args.check:
        if not REFERENCE.is_file() or REFERENCE.read_text(encoding='utf-8') != reference:
            parser.exit(1, f'Stale CLI reference. Regenerate with python scripts/cli-reference.py "{args.binary}"\n')
    else:
        REFERENCE.write_bytes(reference.encode('utf-8'))


if __name__ == '__main__':
    main()
